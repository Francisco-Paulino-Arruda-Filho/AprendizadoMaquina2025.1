#include <random>

using namespace std;

int calcular_custo(const vector<int>& permutacao, 
                   const vector<vector<int>>& fluxo, 
                   const vector<vector<int>>& distancia) {
    int n = permutacao.size();
    int custo = 0;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            custo += fluxo[permutacao[i]][permutacao[j]] * distancia[i][j];
        }
    }
    return custo;
}

vector<vector<int>> vizinhanca_swap(const vector<int>& permutacao) {
    vector<vector<int>> vizinhos;
    int n = permutacao.size();
    for (int i = 0; i < n; i++) {
        for (int j = i + 1; j < n; j++) {
            vector<int> nova = permutacao;
            swap(nova[i], nova[j]);
            vizinhos.push_back(nova);
        }
    }
    return vizinhos;
}

pair<vector<int>, int> busca_local(const vector<vector<int>>& fluxo, const vector<vector<int>>& distancia, int max_iter = 1000) {
    int n = fluxo.size();
    vector<int> atual(n);
    for (int i = 0; i < n; i++) atual[i] = i;

    random_device rd;
    mt19937 g(rd());
    shuffle(atual.begin(), atual.end(), g);

    int custo_atual = calcular_custo(atual, fluxo, distancia);

    for (int iter = 0; iter < max_iter; iter++) {
        vector<int> melhor_vizinho = atual;
        int melhor_custo = custo_atual;
        vector<vector<int>> vizinhos = vizinhanca_swap(atual);

        for (auto& vizinho : vizinhos) {
            int custo_vizinho = calcular_custo(vizinho, fluxo, distancia);
            if (custo_vizinho < melhor_custo) {
                melhor_custo = custo_vizinho;
                melhor_vizinho = vizinho;
            }
        }

        if (melhor_custo < custo_atual) {
            atual = melhor_vizinho;
            custo_atual = melhor_custo;
        } else {
            break; // ótimo local
        }
    }
    return make_pair(atual, custo_atual);
}

