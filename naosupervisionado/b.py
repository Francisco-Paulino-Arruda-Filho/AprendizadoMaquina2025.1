# Plotagem do grafo
G = nx.DiGraph()
n = flow_matrix.shape[0]

# Adicionar arestas com fluxo significativo (filtro para reduzir poluição visual)
for i in range(n):
    for j in range(n):
        if flow_matrix[i][j] > 0:  # Apenas conexões com fluxo positivo
            G.add_edge(i, j, weight=flow_matrix[i][j])

# Configurar layout
pos = nx.spring_layout(G, seed=42, k=0.2)

# Plotar o grafo
plt.figure(figsize=(15, 12))
nx.draw_networkx_nodes(G, pos, node_size=700, node_color='lightblue', edgecolors='black')
nx.draw_networkx_labels(G, pos, font_size=10, font_weight='bold')

# Destacar nós com maior fluxo
node_flux = [sum(flow_matrix[i]) for i in range(n)]
max_flux = max(node_flux)
node_sizes = [300 + 500 * flux / max_flux for flux in node_flux]
nx.draw_networkx_nodes(G, pos, node_size=node_sizes, node_color='skyblue', alpha=0.7)

# Desenhar arestas (espessura proporcional ao fluxo)
edge_weights = [G[u][v]['weight'] for u, v in G.edges()]
nx.draw_networkx_edges(
    G,
    pos,
    width=[0.5 + w/10 for w in edge_weights],
    edge_color='gray',
    alpha=0.7,
    arrowsize=10
)

# Adicionar rótulos nas arestas
edge_labels = {(u, v): d['weight'] for u, v, d in G.edges(data=True)}
nx.draw_networkx_edge_labels(G, pos, edge_labels=edge_labels, font_size=8)

plt.title("Grafo de Fluxo - Instância esc32", fontsize=15)
plt.figtext(0.5, 0.01, f"Total de nós: {n} | Arestas: {len(G.edges())}", ha="center", fontsize=12)
plt.axis('off')
plt.tight_layout()
plt.show()